"""A4: code-like mentions in docs and config files are optional sites, opted in by id."""

from __future__ import annotations

import re

import pytest

from codenav_mcp import write_tools

from .live_support import make_loop_fixture, make_workspace, needs_ty


pytestmark = [pytest.mark.integration, needs_ty]

loop = make_loop_fixture()

_FILES = {
	"src/pkg/__init__.py": "",
	"src/pkg/core.py": "class Widget:\n\tpass\n",
	"docs/api.md": "# API\n\n`Widget` is the main class.\n\nA Widget in prose stays a word.\n\n```python\nw = Widget()\n```\n",
	"docs/zzz.rst": "Use ``Widget`` and `Widget` here.\n",
}


def test_code_like_mentions_in_text_files_get_ids_and_prose_does_not(tmp_path, monkeypatch, loop):
	root = make_workspace(tmp_path, monkeypatch, _FILES)

	preview = str(loop.run_until_complete(write_tools.rename(name="Widget", new_name="Gadget", apply=False)))

	assert re.search(r"\bu1\s+docs/api\.md:3\b", preview), preview
	assert re.search(r"\bu2\s+docs/api\.md:8\b", preview), preview
	assert not re.search(r"docs/api\.md:5\b.*\btext\b", preview.split("Files:")[0]), preview
	assert (root / "docs/api.md").read_text(encoding="utf-8") == _FILES["docs/api.md"]

	text = str(loop.run_until_complete(write_tools.rename(name="Widget", new_name="Gadget", sites=["u1"])))
	assert "Optional text sites included in docs/api.md." in text, text
	assert "`Gadget` is the main class." in (root / "docs/api.md").read_text(encoding="utf-8"), text
	assert "w = Widget()" in (root / "docs/api.md").read_text(encoding="utf-8")  # only u1 was opted in


def test_rename_identifies_generated_docs_and_their_generator(tmp_path, monkeypatch, loop):
	make_workspace(
		tmp_path,
		monkeypatch,
		{
			**_FILES,
			"docs/reference.md": (
				"<!-- Generated by scripts/export_reference.py. Do not edit by hand. -->\n"
				"\n```python\ndef make(cls: Widget): Widget()\n```\n"
			),
		},
	)

	reply = loop.run_until_complete(write_tools.rename(name="Widget", new_name="Gadget", apply=False))

	assert "Regenerate docs/reference.md with its generator (scripts/export_reference.py)" in reply, reply
	assert not re.search(r"\bu\d+\s+docs/reference\.md:", reply), reply
