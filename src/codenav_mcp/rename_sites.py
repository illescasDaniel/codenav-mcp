# Calls whose keyword arguments are attributes of a fake object (`Mock(execute=...)`).
MOCK_FACTORIES = frozenset(
	{"Mock", "MagicMock", "AsyncMock", "NonCallableMock", "NonCallableMagicMock", "PropertyMock", "SimpleNamespace"}
)
_TEST_DIRS = frozenset({"tests", "test", "testing"})
_DOTTED = re.compile(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)+")
# Most keyword arguments one rename asks the type checker about (sequential requests; the rest stay as they are).
_MAX_KEYWORD_LOOKUPS = 300
# Most code-like mentions in docs and config files offered as optional sites in one rename.
_MAX_TEXT_SITES = 60
_GENERATOR = re.compile(r"<!--\s*(?:auto-)?generated by\s+`?([\w./-]+)", re.IGNORECASE)
UNVERIFIED_RUNTIME_USE = "unverified runtime use"
SnippetWidth = 90


class UnknownSitesError(ToolInputError):
	"""`sites=` named an id the plan does not have."""


@dataclass(frozen=True)
class Declaration:
	"""A declaration the rename renames: where its name is (1-based line) and what to call it in a dotted path."""

	path: Path
	line: int
	qualname: str  # `Class.method`, `func`, `Class`


@dataclass
class SitePlan:
	certain: dict[Path, list[TextEdit]] = field(default_factory=dict)
	optional: list[OptionalSite] = field(default_factory=list)
	notes: list[str] = field(default_factory=list)
	certain_count: int = 0
	generated: list[str] = field(default_factory=list)


@dataclass
class _Raw:
	"""An uncertain site before it is numbered."""

	path: Path
	line: int  # 1-based
	column: int  # 0-based UTF-16
	kind: str
	text: str
	edit: TextEdit


def is_test_path(rel: str) -> bool:
	parts = rel.split("/")
	name = parts[-1]
	return (
		any(part in _TEST_DIRS for part in parts[:-1])
		or name.startswith("test_")
		or name.endswith("_test.py")
		or name == "conftest.py"
	)


def dotted_targets(declarations: Sequence[Declaration], roots: Sequence[Path]) -> set[str]:
	"""Every `module.qualname` string that names one of the renamed declarations."""
	names: set[str] = set()
	for declaration in declarations:
		for module in module_names_for(declaration.path, roots):
			names.add(f"{module}.{declaration.qualname}")
	return names


def importer_declarations(edits: dict[Path, list[TextEdit]], old: str, workspace: Path) -> list[Declaration]:
	"""Importers whose `from pkg.mod import old` the rename rewrote: they bind the new name now, so the
	dotted path `importer.old` (a patch target) is renamed too. Aliased imports keep their name and are not listed."""
	found: list[Declaration] = []
	for path, file_edits in edits.items():
		starts = {(e.start_line, e.start_character) for e in file_edits}
		try:
			text = decode_source(path.read_bytes())[0]
			tree = parse_python(text, path.name)
		except (OSError, UnicodeDecodeError, PythonSyntaxError, ValueError, SystemError):
			continue
		lines = source_lines(text)
		for stmt in tree.body:
			if not isinstance(stmt, ast.ImportFrom):
				continue
			for alias in stmt.names:
				if alias.name == old and alias.asname is None:
					row = lines[alias.lineno - 1]
					if (alias.lineno - 1, byte_to_utf16_column(row, alias.col_offset)) in starts:
						found.append(Declaration(path, alias.lineno, old))
	return found


def _in_hidden_dir(rel: str) -> bool:
	return any(part.startswith(".") for part in rel.split("/")[:-1])


def _callee_name(call: ast.Call) -> str:
	func = call.func
	if isinstance(func, ast.Name):
		return func.id
	if isinstance(func, ast.Attribute):
		return func.attr
	return ""


# Which names in a shell heredoc's Python fit a rename: a member is reached as `obj.name` or passed as `name=`; a
# module-level symbol is named bare, imported, or reached as `module.name`; a parameter only as a keyword.
_HEREDOC_ROLES = {
	"member": frozenset({"attr", "keyword", "def"}),
	"top": frozenset({"name", "def", "import", "attr"}),
	"parameter": frozenset({"keyword"}),
}


def _code_like_spans(row: str, old: str, start: int = 0, end: int | None = None) -> list[tuple[int, int]]:
	"""Spans of `old` in `row` that read like code: after a dot, in backticks, or called (`old(`)."""
	spans = []
	for match in re.finditer(rf"(?<!\w){re.escape(old)}(?!\w)", row[: end if end is not None else len(row)]):
		if match.start() < start:
			continue
		before = row[match.start() - 1 : match.start()] if match.start() else ""
		after = row[match.end() : match.end() + 1]
		if "-" in (before, after):
			continue  # part of a hyphenated word such as the CLI flag `--max-matches`, not the Python name
		if before in (".", "`") or after in ("(", "`"):
			spans.append((match.start(), match.end()))
	return spans


def _classes_with_own(tree: ast.Module, rows: list[str], old: str, covered: set[tuple[int, int]]) -> list[range]:
	"""Line ranges (1-based) of the classes that define their own `old` member which this rename does not change.

	A docstring or comment inside such a class that says `old` is about that class's member, not the renamed symbol."""
	ranges = []
	for node in ast.walk(tree):
		if not isinstance(node, ast.ClassDef):
			continue
		for stmt in node.body:
			position = None
			if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef)) and stmt.name == old:
				match = re.search(rf"\bdef\s+({re.escape(old)})\b", rows[stmt.lineno - 1])
				position = (stmt.lineno, match.start(1)) if match else None
			elif isinstance(stmt, (ast.Assign, ast.AnnAssign)):
				targets = stmt.targets if isinstance(stmt, ast.Assign) else [stmt.target]
				for target in targets:
					if isinstance(target, ast.Name) and target.id == old:
						row = rows[target.lineno - 1]
						position = (
							target.lineno,
							len(row.encode("utf-8")[: target.col_offset].decode("utf-8", "ignore")),
						)
			if position and (position[0] - 1, utf16_column(rows[position[0] - 1], position[1])) not in covered:
				ranges.append(range(node.lineno, (node.end_lineno or node.lineno) + 1))
				break
	return ranges


@dataclass
class _FileScan:
	patch: list[TextEdit] = field(default_factory=list)
	# (line, 1-based column, in a Mock-like call, callee name, 1-based (line, column) of the call's start)
	keywords: list[tuple[int, int, bool, str, tuple[int, int]]] = field(default_factory=list)
	optional: list[_Raw] = field(default_factory=list)
	attr_strings: list[AttrString] = field(default_factory=list)


def _scan_python(
	path: Path,
	rel: str,
	old: str,
	new: str,
	dotted: set[str],
	covered: set[tuple[int, int]],
	*,
	test_file: bool,
	strings: bool = True,
	attr_names: bool = False,
	string_tables: bool = False,
	module_exists: Callable[[str], bool] = lambda _module: False,
) -> _FileScan:
	scan = _FileScan()
	try:
		text = decode_source(path.read_bytes())[0]
	except (OSError, UnicodeDecodeError):
		return scan
	if old not in text:
		return scan
	try:
		reject_nul(text, rel)
		tree = parse_python(text, rel)
	except (PythonSyntaxError, ValueError, SystemError):
		return scan
	lines = source_lines(text)
	rows = [line.rstrip("\r\n") for line in lines]
	if attr_names:
		scan.attr_strings = find_attr_strings(text, lines, old)
	if string_tables:
		# A package `__init__` that re-exports the symbol may list it in a string table (`_LAZY_EXPORTS = {"old": ...}`);
		# `__all__` is rewritten with the rename itself.
		for stmt in tree.body:
			if isinstance(stmt, ast.Assign) and any(
				isinstance(t, ast.Name) and t.id == "__all__" for t in stmt.targets
			):
				continue
			if not isinstance(stmt, (ast.Assign, ast.AnnAssign)) or stmt.value is None:
				continue
			for node in ast.walk(stmt.value):
				span = isinstance(node, ast.Constant) and literal_span(lines, node, old)
				if span and (node.lineno - 1, span[0]) not in covered:
					row = rows[node.lineno - 1]
					edit = TextEdit(node.lineno - 1, span[0], node.lineno - 1, span[1], new)
					scan.optional.append(_Raw(path, node.lineno, span[0], "string", row.strip(), edit))

	foreign = _classes_with_own(tree, rows, old, covered)

	def add(kind: str, row_number: int, start: int, end: int) -> None:
		if kind in ("comment", "docstring") and any(row_number in lines_ for lines_ in foreign):
			return
		row = rows[row_number - 1]
		column = utf16_column(row, start)
		edit = TextEdit(row_number - 1, column, row_number - 1, utf16_column(row, end), new)
		scan.optional.append(_Raw(path, row_number, column, kind, row.strip(), edit))

	# Patch targets and comments come from the tokenizer, so multi-line calls and odd quoting are positioned exactly.
	try:
		for token in tokenize.generate_tokens(io.StringIO("\n".join(rows)).readline):
			row_number, col = token.start
			if token.type == tokenize.STRING and strings:
				raw = token.string
				if raw[:1] in ("'", '"') and raw[:3] not in ('"""', "'''") and token.end[0] == row_number:
					content = raw[1:-1]
					if raw[-1] == raw[0] and content.endswith(f".{old}") and _DOTTED.fullmatch(content):
						row = rows[row_number - 1]
						start = utf16_column(row, col + 1 + len(content) - len(old))
						width = len(old.encode("utf-16-le")) // 2
						edit = TextEdit(row_number - 1, start, row_number - 1, start + width, new)
						if content in dotted:
							scan.patch.append(edit)
						elif module_exists(content.rsplit(".", 1)[0]):
							scan.optional.append(_Raw(path, row_number, start, "string", row.strip(), edit))
			elif token.type == tokenize.COMMENT and old in token.string:
				row = rows[row_number - 1]
				for start, end in _code_like_spans(row, old, col):
					if (row_number - 1, utf16_column(row, start)) not in covered:
						add("comment", row_number, start, end)
	except (tokenize.TokenError, IndentationError, SyntaxError):
		pass

	for node in ast.walk(tree):
		if isinstance(node, ast.Call):
			mock = _callee_name(node) in MOCK_FACTORIES
			for keyword in node.keywords:
				if keyword.arg == old:
					line, column = node_position(lines, keyword)
					if (line - 1, column - 1) not in covered:
						scan.keywords.append((line, column, mock, _callee_name(node), node_position(lines, node)))
		if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
			first = node.body[0]
			if (
				isinstance(first, ast.Expr)
				and isinstance(first.value, ast.Constant)
				and isinstance(first.value.value, str)
			):
				constant = first.value
				last_row = constant.end_lineno or constant.lineno
				for row_number in range(constant.lineno, last_row + 1):
					row = rows[row_number - 1]
					start = 0
					end = None
					if row_number == constant.lineno:
						start = len(row.encode("utf-8")[: constant.col_offset].decode("utf-8", errors="ignore"))
					if row_number == last_row and constant.end_col_offset is not None:
						end = len(row.encode("utf-8")[: constant.end_col_offset].decode("utf-8", errors="ignore"))
					for span_start, span_end in _code_like_spans(row, old, start, end):
						add("docstring", row_number, span_start, span_end)
	if test_file:
		for definition in iter_definitions(tree, lines):
			if definition.kind == "method" and definition.name == old:
				line, column = definition_name_position(lines, definition)
				if (line - 1, column - 1) not in covered:
					start = _char_index(rows[line - 1], column - 1)
					add("def", line, start, start + len(old))
	return scan


def _char_index(row: str, utf16_units: int) -> int:
	"""Index into `row` of the character at a UTF-16 offset."""
	count = 0
	for index, char in enumerate(row):
		if count >= utf16_units:
			return index
		count += 2 if ord(char) > 0xFFFF else 1
	return len(row)


def _points_at_renamed(item: dict[str, Any], renamed_at: dict[Path, set[tuple[int, int]]]) -> bool:
	uri = str(item.get("uri") or item.get("targetUri") or "")
	if not uri.startswith("file:"):
		return False
	start = (item.get("range") or item.get("targetSelectionRange") or {}).get("start", {})
	return (int(start.get("line", -1)), int(start.get("character", -1))) in renamed_at.get(
		uri_to_path(uri).resolve(), set()
	)


SplitAttrs = Callable[..., Awaitable[tuple[list[Mention], list[Mention], int]]]


async def plan_v2_sites(
	client: LspClient,
	workspace: Path,
	roots: Sequence[Path],
	*,
	old_name: str,
	new_name: str,
	declarations: Sequence[Declaration],
	is_member: bool,
	parameter: bool,
	link_keywords: bool = True,
	callables: Collection[str] = (),
	owner: Owner | None = None,
	table_files: Collection[Path] = (),
	edits: dict[Path, list[TextEdit]],
	split_attrs: SplitAttrs,
	is_unlinked_attr: Callable[[Mention], bool],
) -> SitePlan:
	"""The certain extra edits and the numbered optional sites for renaming `old_name` -> `new_name`.

	`edits` are the edits already planned (ty's rename plus linked members): their positions are never planned twice."""
	covered = covered_positions(edits)
	plan = SitePlan()
	if not parameter and not is_member:
		# `from pkg.mod import old` becomes `import new` in an importer: patch targets naming the importer's
		# copy (`patch("pkg.use.old")`) must follow.
		declarations = [*declarations, *importer_declarations(edits, old_name, workspace)]
	dotted = set() if parameter else dotted_targets(declarations, roots)
	raws: list[_Raw] = []

	def module_exists(dotted_prefix: str) -> bool:
		parts = dotted_prefix.split(".")
		return any(
			(root / Path(*parts[:end])).with_suffix(".py").is_file()
			or (root / Path(*parts[:end]) / "__init__.py").is_file()
			for root in roots
			for end in range(len(parts), 0, -1)
		)

	string_candidates: list[tuple[Path, AttrString]] = []
	keyword_candidates: list[tuple[Path, int, int, str, tuple[int, int]]] = []
	width = len(old_name.encode("utf-16-le")) // 2
	for path in iter_python_files(workspace):
		rel = relative_name(path, workspace)
		if _in_hidden_dir(rel):
			continue
		resolved = path.resolve()
		scan = _scan_python(
			path,
			rel,
			old_name,
			new_name,
			dotted,
			covered.get(resolved, set()),
			test_file=is_test_path(rel) and is_member,
			strings=not parameter,
			attr_names=owner is not None and not parameter,
			string_tables=resolved in table_files,
			module_exists=module_exists,
		)
		if scan.patch:
			plan.certain.setdefault(resolved, []).extend(scan.patch)
			plan.certain_count += len(scan.patch)
		raws.extend(scan.optional)
		string_candidates.extend((resolved, item) for item in scan.attr_strings)
		for line, column, mock, callee, call_start in scan.keywords:
			if mock:
				if is_member:
					edit = TextEdit(line - 1, column - 1, line - 1, column - 1 + width, new_name)
					raws.append(_Raw(resolved, line, column - 1, "keyword", _line_text(path, line), edit))
			else:
				keyword_candidates.append((resolved, line, column, callee, call_start))
	# Keyword arguments: certain when ty links them to a renamed declaration, otherwise left alone.
	checked = 0
	unreachable = 0
	for path, line, column, callee, call_start in keyword_candidates if link_keywords else []:
		if checked >= _MAX_KEYWORD_LOOKUPS:
			plan.notes.append(
				f"{len(keyword_candidates) - checked} keyword argument(s) named `{old_name}` were not checked"
			)
			break
		checked += 1
		try:
			locations = await client.definition(str(path), line, column)
		except TOOL_ERRORS:
			continue
		if locations and all(_points_at_renamed(item, covered) for item in locations):
			plan.certain.setdefault(path, []).append(
				TextEdit(line - 1, column - 1, line - 1, column - 1 + width, new_name)
			)
			plan.certain_count += 1
		elif not locations and callee in callables and await types_as_never(client, path, *call_start):
			# ty keeps a stale narrowing (`assert x is None` after a call) and types everything below as `Never`: it has
			# no definition for a call there at all. The callee is named like the renamed callable, so offer the keyword.
			edit = TextEdit(line - 1, column - 1, line - 1, column - 1 + width, new_name)
			raws.append(_Raw(path, line, column - 1, "keyword", _line_text(path, line), edit))
			unreachable += 1
	if unreachable:
		plan.notes.append(
			f"{unreachable} keyword argument(s) are in code ty types as `Never` (no type information there): "
			"offered as optional sites by callee name, not verified"
		)
	# `getattr(obj, "old")` and friends: certain when ty resolves the object to the owner, otherwise optional.
	unlooked = 0
	for index, (path, item) in enumerate(string_candidates):
		if owner is None:
			break
		if index >= _MAX_KEYWORD_LOOKUPS:
			unlooked = len(string_candidates) - index
			break
		verdict = await classify(client, workspace, path, item.obj_position, old_name, owner)
		if verdict == "other":
			continue
		edit = TextEdit(item.line - 1, item.start, item.line - 1, item.end, new_name)
		if verdict == "exact":
			plan.certain.setdefault(path, []).append(edit)
			plan.certain_count += 1
		else:
			raws.append(_Raw(path, item.line, item.start, "string", _line_text(path, item.line), edit))
	if unlooked:
		plan.notes.append(f"{unlooked} getattr-style string(s) naming `{old_name}` were not checked")
	# Attribute accesses ty cannot link (`mock.old`): the ones it resolves to another symbol are not candidates at all.
	mentions = find_mentions(workspace, old_name, covered)
	if is_member:
		candidates = sorted(
			(m for m in mentions if is_unlinked_attr(m)),
			key=lambda m: (is_test_path(m.path), m.path, m.line, m.column or 0),
		)
		renamable, other, unchecked = await split_attrs(client, workspace, candidates, covered)
		for mention in renamable:
			column = mention.column or 0
			edit = TextEdit(mention.line - 1, column, mention.line - 1, column + width, new_name)
			path = (workspace / mention.path).resolve()
			kind = "attr"
			if not is_test_path(mention.path) and await types_as_never(client, path, mention.line, column + 1):
				kind = UNVERIFIED_RUNTIME_USE
			raws.append(_Raw(path, mention.line, column, kind, mention.snippet, edit))
		if other:
			plan.notes.append(f"{len(other)} attribute access(es) resolve to another symbol and were left unchanged")
		if unchecked:
			plan.notes.append(
				f"{unchecked} attribute access(es) of `{old_name}` could not be checked and are not listed"
			)
		attr_lines = {(m.path, m.line) for m in candidates}
	else:
		attr_lines = set()
	# Docs, config and other text files: only code-like spans (`old`, old(, .old) are offered, after the Python sites.
	text_sites = 0
	text_lines: dict[Path, list[str]] = {}
	generated_paths: set[Path] = set()
	for mention in mentions:
		if mention.kind != "text":
			continue
		path = (workspace / mention.path).resolve()
		if path in generated_paths:
			continue
		if path not in text_lines:
			try:
				text = decode_source(path.read_bytes())[0]
			except (OSError, UnicodeDecodeError):
				continue
			if generator := _GENERATOR.search(text[:2048]):
				generator_path = generator[1].rstrip(".")
				plan.generated.append(f"Regenerate {mention.path} with its generator ({generator_path}).")
				generated_paths.add(path)
				continue
			text_lines[path] = text.split("\n")
		lines = text_lines[path]
		if mention.line > len(lines):
			continue
		row = lines[mention.line - 1].removesuffix("\r")
		if mention.role is not None:
			# Python in a shell heredoc, parsed: the exact name, if its role fits what is renamed.
			if (
				mention.column is None
				or text_sites >= _MAX_TEXT_SITES
				or mention.role not in _HEREDOC_ROLES["parameter" if parameter else "member" if is_member else "top"]
			):
				continue
			text_sites += 1
			edit = TextEdit(mention.line - 1, mention.column, mention.line - 1, mention.column + width, new_name)
			kind = site_label(mention.role, mention.callee)
			raws.append(_Raw(path, mention.line, mention.column, kind, mention.snippet, edit))
			continue
		for start, end in _code_like_spans(row, old_name):
			if text_sites >= _MAX_TEXT_SITES:
				break
			text_sites += 1
			column = utf16_column(row, start)
			edit = TextEdit(mention.line - 1, column, mention.line - 1, utf16_column(row, end), new_name)
			raws.append(_Raw(path, mention.line, column, "text", mention.snippet, edit))
	if text_sites >= _MAX_TEXT_SITES:
		plan.notes.append(
			f"more than {_MAX_TEXT_SITES} code-like mentions in non-Python files; only the first are offered"
		)
	listed = {(relative_name(raw.path, workspace), raw.line) for raw in raws} | {
		(relative_name(path, workspace), edit.start_line + 1) for path, es in plan.certain.items() for edit in es
	}
	# A string on a line the rename already edits (`__all__ = ["old"]`) is handled, not left over.
	edited = {(relative_name(path, workspace), e.start_line + 1) for path, es in edits.items() for e in es}
	rest = [
		m
		for m in mentions
		if (m.path, m.line) not in listed
		and (m.path, m.line) not in attr_lines
		and not (m.kind == "string" and (m.path, m.line) in edited)
	]
	if rest:
		counts: dict[str, int] = {}
		for mention in rest:
			counts[mention.kind] = counts.get(mention.kind, 0) + 1
		labels = {
			"code": "bare name",
			"string": "string",
			"comment": "comment",
			"text": "non-Python file",
			"attr": "attribute access",
		}
		parts = [f"{count} {labels[kind]}{'s' if count != 1 else ''}" for kind, count in counts.items()]
		examples = ", ".join(f"{m.path}:{m.line}" for m in rest[:3])
		plan.notes.append(
			f"`{old_name}` also appears in {', '.join(parts)} (not listed: plain words, other symbols), e.g. {examples}"
		)
	unique: dict[tuple[Path, int, int, str], _Raw] = {}
	for raw in raws:
		unique.setdefault((raw.path, raw.line, raw.column, raw.kind), raw)
	ordered = sorted(
		unique.values(),
		key=lambda r: (
			r.kind != UNVERIFIED_RUNTIME_USE,
			r.kind == "text",
			relative_name(r.path, workspace),
			r.line,
			r.column,
			r.kind,
		),
	)
	plan.optional = [
		OptionalSite(f"u{number}", relative_name(raw.path, workspace), raw.line, raw.kind, raw.text[:140], raw.edit)
		for number, raw in enumerate(ordered, 1)
	]
	return plan


def _line_text(path: Path, line: int) -> str:
	try:
		row = decode_source(path.read_bytes())[0].split("\n")[line - 1].removesuffix("\r")
		return row.strip()
	except (OSError, UnicodeDecodeError, IndexError):
		return ""


def select_sites(optional: Sequence[OptionalSite], sites: Sequence[str] | None) -> list[OptionalSite]:
	"""The optional sites `sites=` asks for (`"all"` or ids); an unknown id lists the valid ones."""
	if not sites:
		return []
	if any(site.lower() == "all" for site in sites):
		return list(optional)
	known = {site.id: site for site in optional}
	unknown = [site for site in sites if site not in known]
	if unknown:
		valid = f"valid ids: {', '.join(known)}" if known else "this rename has no optional sites"
		raise UnknownSitesError(f"unknown site id(s) {', '.join(repr(s) for s in unknown)}; {valid}")
	return [known[site] for site in dict.fromkeys(sites)]


def format_site(site: OptionalSite) -> str:
	text = site.text if len(site.text) <= SnippetWidth else site.text[: SnippetWidth - 3] + "..."
	return f"{site.id:<3} {site.path}:{site.line}  {site.kind}  {text}"
